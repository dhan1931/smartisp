-- utf8mb4_unicode_ci ignora mayúsculas y tildes, como normalizeCategoryText de la tienda.
CREATE TEMPORARY TABLE IF NOT EXISTS tmp_046_sin_familia (
  id VARCHAR(191) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL PRIMARY KEY,
  n VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL
) ENGINE=MEMORY;

DELETE FROM tmp_046_sin_familia;

INSERT INTO tmp_046_sin_familia (id, n)
  SELECT CONVERT(id USING utf8mb4), CONVERT(TRIM(REPLACE(name, '_', ' ')) USING utf8mb4)
  FROM categories_rows
  WHERE macro_group_id = 'otros' AND (parent_category_id IS NULL OR parent_category_id = '') AND TRIM(REPLACE(name, '_', ' ')) <> '';

UPDATE categories_rows c
  JOIN tmp_046_sin_familia t ON t.id = CONVERT(c.id USING utf8mb4) COLLATE utf8mb4_unicode_ci
  SET c.macro_group_id = COALESCE(
    (SELECT r.group_id FROM tmp_046_reglas r
      JOIN category_macro_groups g ON CONVERT(g.id USING utf8mb4) COLLATE utf8mb4_unicode_ci = r.group_id
      WHERE r.texto = t.n
         OR (r.tipo = 2 AND (t.n LIKE CONCAT('%', r.texto, '%') OR r.texto LIKE CONCAT('%', t.n, '%')))
      ORDER BY CASE WHEN r.texto = t.n THEN r.tipo ELSE 3 END, r.orden
      LIMIT 1),
    c.macro_group_id)
  WHERE c.macro_group_id = 'otros';

-- Las subcategorías siguen la familia de su principal.
UPDATE categories_rows h
  JOIN categories_rows p ON p.id = h.parent_category_id
  SET h.macro_group_id = p.macro_group_id
  WHERE p.macro_group_id IS NOT NULL AND p.macro_group_id <> '' AND NOT (h.macro_group_id <=> p.macro_group_id);

DROP TEMPORARY TABLE IF EXISTS tmp_046_sin_familia;

DROP TEMPORARY TABLE IF EXISTS tmp_046_reglas;
